import 'package:looseleaf_ui/src/components/menu/menu.dart';

/// The slip a dropdown menu drops: an [InkMenuContent].
///
/// Mirrors `DropdownMenuContent` in upstream
/// `src/components/ui/dropdown-menu.tsx`.
typedef DropdownMenuContent = InkMenuContent;

/// Groups rows: an [InkMenuGroup].
typedef DropdownMenuGroup = InkMenuGroup;

/// A typewriter heading: an [InkMenuLabel].
typedef DropdownMenuLabel = InkMenuLabel;

/// A row: an [InkMenuItem].
typedef DropdownMenuItem = InkMenuItem;

/// A toggle row with a pencil box: an [InkMenuCheckboxItem].
typedef DropdownMenuCheckboxItem = InkMenuCheckboxItem;

/// Holds radio rows: an [InkMenuRadioGroup].
typedef DropdownMenuRadioGroup = InkMenuRadioGroup;

/// One choice with a pencil ring: an [InkMenuRadioItem].
typedef DropdownMenuRadioItem = InkMenuRadioItem;

/// A pencil rule between groups: an [InkMenuSeparator].
typedef DropdownMenuSeparator = InkMenuSeparator;

/// Keys drawn as keycaps at a row's end: an [InkMenuShortcut].
typedef DropdownMenuShortcut = InkMenuShortcut;

/// A nested menu: an [InkMenuSub].
typedef DropdownMenuSub = InkMenuSub;

/// The row that opens a sub-menu: an [InkMenuSubTrigger].
typedef DropdownMenuSubTrigger = InkMenuSubTrigger;

/// A sub-menu's slip: an [InkMenuSubContent].
typedef DropdownMenuSubContent = InkMenuSubContent;
