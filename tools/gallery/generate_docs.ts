// Writes the gallery's component and block docs from upstream's docs metadata
// (src/docs/meta/*.ts and src/docs/content/blocks/*.meta.ts).
//
// Usage: bun tools/gallery/generate_docs.ts <path to a looseleaf checkout>
import { mkdirSync, readdirSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const checkout = resolve(process.argv[2] ?? ".upstream/looseleaf")
const root = resolve(import.meta.dir, "../..")
const feature = join(root, "modules/gallery/lib/features")
const docsDir = join(feature, "components/docs")
const blocksDir = join(feature, "blocks/docs")

const categories: Record<string, string> = {
  Actions: "actions",
  Forms: "forms",
  Feedback: "feedback",
  Overlays: "overlays",
  Navigation: "navigation",
  Layout: "layout",
  "Data display": "dataDisplay",
  Charts: "charts",
  Paper: "paper",
  Marks: "marks",
  "Stickers & doodles": "stickersDoodles",
  Chat: "chat",
  Interactive: "interactive",
  Typography: "typography",
  Icons: "icons",
}

const reactOnlyProps = new Set(["asChild", "className", "ref", "style"])

const dart = (value: string) =>
  "'" + value.replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("$", "\\$").replaceAll("\n", "\\n") + "'"

const camel = (slug: string) => slug.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
const snake = (slug: string) => slug.replaceAll("-", "_")

interface Prop {
  name: string
  type: string
  default?: string
  description: string
  required?: boolean
}

interface Part {
  name: string
  description?: string
  props?: Prop[]
}

function prop(p: Prop, indent: string): string {
  const fields = [
    `name: ${dart(p.name)}`,
    `type: ${dart(p.type)}`,
    p.default === undefined ? null : `defaultValue: ${dart(p.default)}`,
    `description: ${dart(p.description)}`,
    p.required ? "required: true" : null,
  ].filter((f) => f !== null)
  return `${indent}PropDoc(\n${fields.map((f) => `${indent}  ${f},\n`).join("")}${indent}),\n`
}

function part(p: Part): string {
  const props = (p.props ?? []).filter((q) => !reactOnlyProps.has(q.name))
  const lines = [`    PartDoc(\n`, `      name: ${dart(p.name)},\n`]
  if (p.description) lines.push(`      description: ${dart(p.description)},\n`)
  if (props.length > 0) lines.push(`      props: [\n${props.map((q) => prop(q, "        ")).join("")}      ],\n`)
  lines.push(`    ),\n`)
  return lines.join("")
}

mkdirSync(docsDir, { recursive: true })
const metaDir = join(checkout, "src/docs/meta")
const slugs: string[] = []
for (const file of readdirSync(metaDir).filter((f) => f.endsWith(".ts")).sort()) {
  const doc = (await import(join(metaDir, file))).default
  const name = `${camel(doc.slug)}Doc`
  slugs.push(doc.slug)
  const body = [
    `/// Mirrors \`src/docs/meta/${file}\`. Generated by tools/gallery/generate_docs.ts.\n`,
    `const ${name} = ComponentDoc(\n`,
    `  slug: ${dart(doc.slug)},\n`,
    `  title: ${dart(doc.title)},\n`,
    `  category: ComponentCategory.${categories[doc.category]},\n`,
    `  description: ${dart(doc.description)},\n`,
    doc.status ? `  status: ComponentStatus.${doc.status === "new" ? "isNew" : doc.status},\n` : "",
    doc.upstream ? `  upstream: ${dart(doc.upstream)},\n` : "",
    doc.parts.length > 0 ? `  parts: [\n${doc.parts.map(part).join("")}  ],\n` : "",
    doc.a11y?.length ? `  a11y: [\n${doc.a11y.map((l: string) => `    ${dart(l)},\n`).join("")}  ],\n` : "",
    doc.related?.length ? `  related: [${doc.related.map(dart).join(", ")}],\n` : "",
    `);\n`,
  ].join("")
  writeFileSync(
    join(docsDir, `${snake(doc.slug)}_doc.dart`),
    `import 'package:gallery/features/components/models/models.dart';\n\n${body}`,
  )
}

const imports = [...slugs].sort((a, b) => (`${snake(a)}_doc.dart` < `${snake(b)}_doc.dart` ? -1 : 1)).map((s) => `export 'package:gallery/features/components/docs/${snake(s)}_doc.dart';\n`).join("")
writeFileSync(join(docsDir, "docs.dart"), imports)
writeFileSync(
  join(docsDir, "all_component_docs.dart"),
  [
    `import 'package:gallery/features/components/docs/docs.dart';\n`,
    `import 'package:gallery/features/components/models/models.dart';\n\n`,
    `/// Every upstream component doc, by slug. Generated by tools/gallery/generate_docs.ts.\n`,
    `const Map<String, ComponentDoc> allComponentDocs = {\n`,
    slugs.map((s) => `  ${dart(s)}: ${camel(s)}Doc,\n`).join(""),
    `};\n`,
  ].join(""),
)

mkdirSync(blocksDir, { recursive: true })
const blockMeta = join(checkout, "src/docs/content/blocks")
const blocks: string[] = []
for (const file of readdirSync(blockMeta).filter((f) => f.endsWith(".meta.ts")).sort()) {
  const slug = file.replace(/\.meta\.ts$/, "")
  if (slug.endsWith("-shared")) continue
  const doc = (await import(join(blockMeta, file))).default
  const fields = [
    `slug: ${dart(slug)}`,
    `title: ${dart(doc.title)}`,
    doc.description ? `description: ${dart(doc.description)}` : null,
    doc.tags?.length ? `tags: [${doc.tags.map(dart).join(", ")}]` : null,
    doc.surface === "desk" ? "surface: BlockSurface.desk" : null,
  ].filter((f) => f !== null)
  blocks.push(`  BlockDoc(\n${fields.map((f) => `    ${f},\n`).join("")}  ),\n`)
}
writeFileSync(
  join(blocksDir, "all_block_docs.dart"),
  [
    `import 'package:gallery/features/blocks/models/models.dart';\n\n`,
    `/// Every upstream block, from \`src/docs/content/blocks/*.meta.ts\`. Generated by\n/// tools/gallery/generate_docs.ts.\n`,
    `const List<BlockDoc> allBlockDocs = [\n`,
    blocks.join(""),
    `];\n`,
  ].join(""),
)

const foundationsDir = join(feature, "foundations/docs")
mkdirSync(foundationsDir, { recursive: true })
const { FOUNDATIONS } = await import(join(checkout, "src/docs/core/foundations.ts"))
const topics = FOUNDATIONS.map((t: any) => {
  const fields = [
    `slug: ${dart(t.slug)}`,
    `title: ${dart(t.title)}`,
    `summary: ${dart(t.summary)}`,
    `facts: [\n${t.facts.map((f: string) => `      ${dart(f)},\n`).join("")}    ]`,
    t.swatches ? `swatches: [\n${t.swatches.map((s: any) => `      (token: ${dart(s.token.replace(/^--ll-/, ""))}, label: ${dart(s.label)}),\n`).join("")}    ]` : null,
    t.fonts ? `fonts: [\n${t.fonts.map((f: any) => `      (token: ${dart(f.token)}, label: ${dart(f.label)}, role: ${dart(f.role)}),\n`).join("")}    ]` : null,
    t.see ? `see: [${t.see.map((s: any) => `(label: ${dart(s.label)}, slug: ${dart(s.to.replace("/foundations/", ""))})`).join(", ")}]` : null,
  ].filter((f) => f !== null)
  return `  FoundationTopic(\n${fields.map((f) => `    ${f},\n`).join("")}  ),\n`
})
writeFileSync(
  join(foundationsDir, "foundation_topics.dart"),
  [
    `import 'package:gallery/features/foundations/models/models.dart';\n\n`,
    `/// The foundations topics of upstream \`src/docs/core/foundations.ts\`. Generated by\n/// tools/gallery/generate_docs.ts.\n`,
    `const List<FoundationTopic> foundationTopics = [\n`,
    topics.join(""),
    `];\n`,
  ].join(""),
)
