function glyphFont(name: string, f: { cap: number; adv: Record<string, number>; d: Record<string, string> }): string {
  const adv = Object.keys(f.adv).map((k) => `${str(k)}: ${num(f.adv[k])}`).join(', ')
  const d = Object.keys(f.d).map((k) => `    ${str(k)}: ${str(f.d[k])},`).join('\n')
  return `const GlyphFont ${name} = GlyphFont(\n  cap: ${num(f.cap)},\n  adv: {${adv}},\n  d: {\n${d}\n  },\n);\n`
}
write(
  'text/glyph_data.dart',
  `${header(upstream('glyphs.ts'))}\nimport 'package:looseleaf_ink/src/art/text/glyph_font.dart';\n\n` +
    `/// The hand lettering (Kevin Sans outlines), units per 1000 em.\n///\n/// Mirrors \`GLYPHS_HAND\` in \`${upstream('glyphs.ts')}\`.\n` +
    glyphFont('glyphsHand', GLYPH_FONTS.hand) +
    `\n/// The typewriter lettering for stamps, units per 1000 em.\n///\n/// Mirrors \`GLYPHS_TYPE\` in \`${upstream('glyphs.ts')}\`.\n` +
    glyphFont('glyphsType', GLYPH_FONTS.type),
)

