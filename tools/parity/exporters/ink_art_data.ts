// Generates the Dart art catalog (icons, doodles, stickers, mascot, scenes, props and the lettering glyphs)
// from the evaluated upstream tables, into packages/looseleaf_ink/lib/src/art/. Mascot poses are built by
// code upstream (`pose()`), so the generator writes their evaluated definitions.
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { iconBatches, ICON_ALIASES } from '@/lib/ink/art/icons'
import { doodleBatches } from '@/lib/ink/art/doodles'
import { stickerBatches } from '@/lib/ink/art/stickers'
import { mascotBatches, mascotProps } from '@/lib/ink/art/mascots'
import { sceneBatches } from '@/lib/ink/art/scenes'
import { propBatches } from '@/lib/ink/art/props'
import { GLYPH_FONTS } from '@/lib/ink/art/glyphs'

const root = process.env.LOOSELEAF_UI_ROOT
if (!root) throw new Error('LOOSELEAF_UI_ROOT is not set; run through export.sh')
const artDir = 'packages/looseleaf_ink/lib/src/art'
const written: string[] = []

const header = (source: string): string =>
  `// GENERATED by tools/parity/exporters/ink_art_data.ts from Looseleaf's ${source}. Do not edit.\n`

function write(rel: string, text: string): void {
  const file = join(root as string, artDir, rel)
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
  written.push(file)
  console.log(`    ${artDir}/${rel}`)
}

const camel = (s: string): string => s.replace(/[-_]([a-z0-9])/g, (_, c: string) => c.toUpperCase())
const snake = (s: string): string => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/-/g, '_').toLowerCase()
const cap = (s: string): string => s[0].toUpperCase() + s.slice(1)

function str(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`
}

function num(v: unknown): string {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`not a finite number: ${String(v)}`)
  return String(v)
}

const PAINT: Record<string, string> = {}
for (const id of [
  'ink', 'ink-soft', 'ink-you', 'pencil', 'pencil-mark', 'red', 'green', 'marker', 'hi', 'focus', 'paper', 'paper-shade', 'slip', 'card',
  'graph', 'kraft', 'check', 'photo', 'desk', 'desk-deep', 'rule-blue', 'rule-red', 'pad', 'pad-rule', 'check-rule', 'ink-muted',
  'pencil-text', 'orange-text', 'hi-deep', 'tape', 'tape-edge', 'tomato', 'tangerine', 'lemon', 'grass', 'teal', 'sky', 'grape',
  'bubblegum', 'sticky-yellow', 'sticky-green', 'sticky-orange', 'sticky-pink', 'sticky-blue',
]) PAINT[id] = `PaintKey.${camel(id)}`

function paintKey(id: unknown): string {
  const key = PAINT[id as string]
  if (!key) throw new Error(`unknown paint "${String(id)}"`)
  return key
}

function colour(c: unknown): string {
  if (c === 'acc') return 'ArtColour.acc'
  if (c === 'sil') return 'ArtColour.sil'
  const s = c as string
  if (s.endsWith('~')) return `ArtColour.wash(${paintKey(s.slice(0, -1))})`
  return `ArtColour(${paintKey(s)})`
}

function hand(h: unknown): string {
  const o = h as Record<string, unknown>
  const args: string[] = []
  for (const k of Object.keys(o)) {
    if (k === 'start') args.push(`start: StrokeStart.${o.start as string}`)
    else if (k === 'end') args.push(`end: StrokeEnd.${o.end as string}`)
    else if (k === 'taper') args.push(`taper: ${num(o.taper)}`)
    else throw new Error(`unknown hand key ${k}`)
  }
  return `Hand(${args.join(', ')})`
}

/** Positional arguments, dropping trailing undefined ones; a hole before a set value becomes null. */
function positional(values: unknown[], fmt: Array<(v: unknown) => string>): string {
  let last = values.length - 1
  while (last >= 0 && values[last] === undefined) last--
  const out: string[] = []
  for (let i = 0; i <= last; i++) out.push(values[i] === undefined ? 'null' : fmt[i](values[i]))
  return out.join(', ')
}

const S = (v: unknown): string => str(v as string)
const N = (v: unknown): string => num(v)

function part(p: readonly unknown[]): string {
  switch (p[0]) {
    case 'f':
      return `FillPart(${positional(p.slice(1, 4), [colour, S, N])})`
    case 's':
      return `StrokePart(${positional(p.slice(1, 4), [S, N, hand])})`
    case 'c':
      return `ColourStrokePart(${positional(p.slice(1, 5), [colour, S, N, hand])})`
    case 'd':
      return `DotPart(${positional(p.slice(1, 4), [N, N, N])})`
    case 'h':
      return `HighlightPart(${positional(p.slice(1, 3), [S, N])})`
    case 't':
      return `TextPart(${positional(p.slice(1, 7), [S, N, N, N, colour, (v) => `LetterFont.${v as string}`])})`
  }
  throw new Error(`unknown part ${JSON.stringify(p)}`)
}

const parts = (list: unknown): string => `[${(list as unknown[][]).map(part).join(', ')}]`
const strings = (list: unknown): string => `[${(list as string[]).map(str).join(', ')}]`

function grid(g: unknown): string {
  if (g === 24) return 'ArtGrid.icon'
  if (g === 64) return 'ArtGrid.doodle'
  const [w, h] = g as number[]
  return `ArtGrid(${num(w)}, ${num(h)})`
}

const ACCENTS = new Set(['tomato', 'tangerine', 'lemon', 'grass', 'teal', 'sky', 'grape', 'bubblegum', 'hi', 'kraft'])
function accent(a: unknown): string {
  if (!ACCENTS.has(a as string)) throw new Error(`unknown accent ${String(a)}`)
  return `ArtAccent.${a as string}`
}

const RULES = new Set(['ruled', 'lines', 'index', 'graph', 'dots', 'none'])

function layer(l: Record<string, unknown>): string {
  const args: string[] = []
  for (const k of Object.keys(l)) {
    const v = l[k]
    if (v === undefined) continue
    if (k === 'ref' || k === 'edge' || k === 'tone' || k === 'note') args.push(`${k}: ${str(v as string)}`)
    else if (k === 'at') args.push(`at: (${num((v as number[])[0])}, ${num((v as number[])[1])})`)
    else if (k === 'size' || k === 'rot' || k === 'aspect' || k === 'nib') args.push(`${k}: ${num(v)}`)
    else if (k === 'flip' || k === 'peel' || k === 'hi') args.push(`${k}: ${String(v as boolean)}`)
    else if (k === 'rules') {
      if (!RULES.has(v as string)) throw new Error(`unknown rules ${String(v)}`)
      args.push(`rules: SceneRules.${v === 'index' ? 'indexCard' : (v as string)}`)
    } else if (k === 'accent') args.push(`accent: ${accent(v)}`)
    else if (k === 'parts') args.push(`parts: ${parts(v)}`)
    else throw new Error(`unknown scene layer key ${k}`)
  }
  return `SceneLayer(${args.join(', ')})`
}

const KINDS = new Set(['icon', 'doodle', 'sticker', 'mascot', 'prop', 'scene'])

function def(d: Record<string, unknown>): string {
  const scene = d.kind === 'scene'
  const args: string[] = []
  for (const k of Object.keys(d)) {
    const v = d[k]
    if (v === undefined) continue
    switch (k) {
      case 'grid':
        args.push(`grid: ${grid(v)}`)
        break
      case 'parts':
      case 'small':
      case 'micro':
      case 'hi':
        args.push(`${k}: ${parts(v)}`)
        break
      case 'accent':
        args.push(`accent: ${accent(v)}`)
        break
      case 'nibK':
      case 'tilt':
        args.push(`${k}: ${num(v)}`)
        break
      case 'tags':
        args.push(`tags: ${strings(v)}`)
        break
      case 'shade':
      case 'mirror':
        args.push(`${k}: ${String(v as boolean)}`)
        break
      case 'rtl':
        if (v !== 'flip') throw new Error(`unknown rtl ${String(v)}`)
        args.push('rtlFlip: true')
        break
      case 'kind':
        if (!KINDS.has(v as string)) throw new Error(`unknown kind ${String(v)}`)
        if (!scene) args.push(`kind: ArtKind.${v as string}`)
        break
      case 'layers':
      case 'layersSmall':
        if (!scene) throw new Error(`${k} outside a scene`)
        args.push(`${k}: [${(v as Record<string, unknown>[]).map(layer).join(', ')}]`)
        break
      default:
        throw new Error(`unknown def key ${k}`)
    }
  }
  return `${scene ? 'SceneDef' : 'ArtDef'}(${args.join(', ')})`
}

const STAMP_INK: Record<string, string> = { red: 'StampPadInk.red', 'ink-you': 'StampPadInk.inkYou', green: 'StampPadInk.green', ink: 'StampPadInk.ink' }
const STAMP_SHAPE: Record<string, string> = { rect: 'StampShape.rect', round: 'StampShape.round', burst: 'StampShape.burst', void: 'StampShape.voided' }

function stampGen(d: Record<string, unknown>): string {
  const opts: string[] = []
  for (const k of Object.keys(d)) {
    const v = d[k]
    if (k === 'gen' || k === 'text' || k === 'shape' || k === 'kind' || v === undefined) continue
    if (k === 'sub' || k === 'ring') opts.push(`${k}: ${str(v as string)}`)
    else if (k === 'ink') opts.push(`ink: ${STAMP_INK[v as string]}`)
    else if (k === 'w' || k === 'h' || k === 'tilt' || k === 'wear') opts.push(`${k}: ${num(v)}`)
    else if (k === 'stars') opts.push(`stars: ${num(v)}`)
    else if (k === 'ghost' || k === 'dashed') opts.push(`${k}: ${String(v as boolean)}`)
    else if (k === 'tags') opts.push(`tags: ${strings(v)}`)
    else throw new Error(`unknown stamp key ${k}`)
  }
  return `StampGen(${str(d.text as string)}, ${STAMP_SHAPE[d.shape as string]}, opts: StampOpts(${opts.join(', ')}))`
}

function stickerDef(d: Record<string, unknown>): string {
  if (d.gen === 'stamp') return stampGen(d)
  if (d.gen !== undefined) throw new Error(`unsupported generator ${String(d.gen)} in the data`)
  return def(d)
}

type Table = Record<string, Record<string, unknown>>

interface Batch {
  name: string
  file: string
  source: string
  table: Table
  constName?: string
}

function imports(body: string): string {
  const lines = ["import 'package:looseleaf_ink/src/art/model/model.dart';"]
  if (/PaintKey\.|StrokeStart\.|StrokeEnd\./.test(body)) lines.push("import 'package:looseleaf_ink/src/core/core.dart';")
  return lines.join('\n')
}

function writeBatch(folder: string, kind: string, type: string, b: Batch, entry: (d: Record<string, unknown>) => string): string {
  const constName = b.constName ?? `${camel(b.name)}${cap(kind)}`
  const rows = Object.keys(b.table).map((id) => `  ${str(id)}: ${entry(b.table[id])},`).join('\n')
  const body = `const Map<String, ${type}> ${constName} = {\n${rows}\n};\n`
  write(
    `${folder}/${b.file}.dart`,
    `${header(b.source)}\n${imports(body)}\n\n/// The \`${b.name}\` ${kind}.\n///\n/// Mirrors \`${b.name}\` in \`${b.source}\`.\n${body}`,
  )
  return constName
}

function writeCatalog(o: {
  folder: string
  kind: string
  type: string
  all: string
  batchesName: string
  source: string
  batches: Batch[]
  entry: (d: Record<string, unknown>) => string
  extra?: string
  extraExports?: string[]
}): void {
  const names = o.batches.map((b) => ({ b, c: writeBatch(o.folder, o.kind, o.type, b, o.entry) }))
  const seen = new Set<string>()
  for (const { b } of names) for (const id of Object.keys(b.table)) {
    if (seen.has(id)) throw new Error(`duplicate ${o.kind} id ${id}`)
    seen.add(id)
  }
  const batches = names.map(({ b, c }) => `  ${str(b.name)}: ${c},`).join('\n')
  const spread = names.map(({ c }) => `  ...${c},`).join('\n')
  const exports = [...names.map(({ b }) => `${o.folder}/${b.file}.dart`), `${o.folder}/${o.folder}_catalog.dart`, ...(o.extraExports ?? [])]
  const catalog =
    `${header(o.source)}\n` +
    [...(names.length ? [`import 'package:looseleaf_ink/src/art/${o.folder}/${o.folder}.dart';`] : []), "import 'package:looseleaf_ink/src/art/model/model.dart';"]
      .sort()
      .join('\n') +
    '\n\n' +
    `/// Every ${o.kind} batch by name.\n///\n/// Mirrors \`${o.batchesName}\` in \`${o.source}\`.\n` +
    `const Map<String, Map<String, ${o.type}>> ${o.batchesName} = {\n${batches}\n};\n\n` +
    `/// Every ${o.kind} by id.\n///\n/// Mirrors \`${o.all}\` in \`${o.source}\`.\n` +
    `const Map<String, ${o.type}> ${o.all} = {\n${spread}\n};\n` +
    (o.extra ?? '')
  write(`${o.folder}/${o.folder}_catalog.dart`, catalog)
  const barrel = exports.sort().map((e) => `export 'package:looseleaf_ink/src/art/${e}';`).join('\n')
  write(`${o.folder}/${o.folder}.dart`, `${header(o.source)}\n${barrel}\n`)
}

const upstream = (p: string): string => `src/lib/ink/art/${p}`

const ICON_FILES: Record<string, string> = {
  arrows: 'arrows', marks: 'marks', status: 'status', layout: 'layout', files: 'files', comms: 'comms', devData: 'dev-data',
  textNatureMisc: 'text-nature-misc', media: 'media', commerceTime: 'commerce-time',
}
const batchesOf = (src: Record<string, unknown>, folder: string, files: Record<string, string>): Batch[] =>
  Object.keys(src).map((name) => {
    const file = files[name]
    if (!file) throw new Error(`no file for batch ${name}`)
    return { name, file: snake(file), source: upstream(`${folder}/${file}.ts`), table: src[name] as Table }
  })

